#include "ft_printf.h"

int	ft_putnbr(int n)
{
	int	co;

	co = 0;
	if (n == -2147483648)
	{
		write(1, "-2147483648", 11);
		return (11);
	}
	if (n < 0)
	{
		write(1, "-", 1);
		n *= -1;
		co++;
	}
	if (n / 10 != 0)
		co += ft_putnbr(n / 10);
	write(1, (char []){n % 10 + '0'}, 1);
	return (co + 1);
}
