#include "ft_printf.h"

int	ft_putunbr(unsigned int n)
{
	int	co;

	co = 0;
	if (n / 10 != 0)
		co += ft_putunbr(n / 10);
	write(1, (char []){n % 10 + '0'}, 1);
	return (co + 1);
}
